import { execFileSync } from 'node:child_process';
import { DatabaseSync } from 'node:sqlite';
import { writeFileSync } from 'node:fs';

// Offline audit only: untrusted answers run inside a disposable, networkless
// PostgreSQL container, never against the application database.
const image = 'postgres:15-alpine';
const name = `zxbench-so-postgres-${process.pid}`;
const call = (args, input) => execFileSync('docker', args, {
  input, encoding: 'utf8', timeout: 10000, maxBuffer: 1024 * 1024,
  windowsHide: true,
});
const psql = (database, sql) => call(['exec',
  '-e', 'PGOPTIONS=-c statement_timeout=1500', name,
  'psql', '-X', '-q', '-t', '-A', '-v', 'ON_ERROR_STOP=1',
  '-U', 'postgres', '-d', database, '-c', sql]);

const fixture = `
CREATE TABLE products (product_id integer PRIMARY KEY, sku text, name text,
  stock integer NOT NULL, reorder_level integer NOT NULL, price numeric);
CREATE TABLE warehouses (warehouse_id integer NOT NULL, product_id integer NOT NULL,
  quantity integer NOT NULL, PRIMARY KEY (warehouse_id, product_id));
CREATE TABLE restock_log (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id integer NOT NULL, warehouse_id integer NOT NULL,
  added_quantity integer NOT NULL, created_at timestamp DEFAULT now(),
  UNIQUE (product_id, warehouse_id));
INSERT INTO products VALUES
  (1,'A','A',2,10,1.0),(2,'B','B',1,7,2.0),(3,'C','C',12,10,3.0);
INSERT INTO warehouses VALUES (10,1,20),(11,1,9),(20,2,15),(30,3,10);
`;
const existingLog = `INSERT INTO restock_log(product_id,warehouse_id,added_quantity)
  VALUES (1,10,3),(1,11,3);`;
const snapshot = `SELECT json_build_object(
  'stocks',(SELECT json_agg(json_build_array(product_id,stock) ORDER BY product_id) FROM products),
  'logs',(SELECT json_agg(json_build_array(product_id,warehouse_id,added_quantity)
     ORDER BY product_id,warehouse_id) FROM restock_log));`;
const rankingFixture = `
CREATE TABLE users (id integer PRIMARY KEY,name text,city text);
CREATE TABLE orders (id integer PRIMARY KEY,user_id integer,order_no text,
  amount numeric,status text,created_at timestamp);
INSERT INTO users VALUES
  (1,'A1','甲城'),(2,'A2','甲城'),(3,'A3','甲城'),(4,'A4','甲城'),
  (5,'B1','乙城'),(6,'B2','乙城'),(7,'B3','乙城'),(8,'B4','乙城');
INSERT INTO orders VALUES
  (1,1,'A1-100',100,'paid','2024-03-01'),
  (2,1,'A1-95',95,'paid','2024-03-31'),
  (3,2,'A2-90',90,'paid','2024-03-02'),
  (4,3,'A3-80',80,'paid','2024-03-03'),
  (5,4,'A4-70',70,'paid','2024-03-04'),
  (6,4,'A4-old',500,'paid','2024-02-29'),
  (7,5,'B1-60',60,'paid','2024-03-05'),
  (8,5,'B1-55',55,'paid','2024-03-06'),
  (9,6,'B2-50',50,'paid','2024-03-07'),
  (10,7,'B3-40',40,'paid','2024-03-08'),
  (11,8,'B4-30',30,'paid','2024-03-09'),
  (12,8,'B4-late',500,'paid','2024-04-01');`;
const db = new DatabaseSync('apps/data/zxbench.db', { readOnly: true });
const rows = db.prepare(`SELECT r.evalRunId, r.modelOutput FROM ScenarioResult r
  JOIN EvalRun e ON e.id=r.evalRunId WHERE e.status='completed'
  AND r.scenarioId=? AND r.modelOutput IS NOT NULL
  ORDER BY e.createdAt DESC LIMIT 6`);
const restockRows = rows.all('SO-CN-034');
const rankingRows = rows.all('SO-CN-013');
db.close();

const restockReport = [], rankingReport = [];
try {
  call(['run', '--rm', '-d', '--name', name, '--network', 'none',
    '--cpus', '1', '--memory', '256m', '--pids-limit', '100',
    '-e', 'POSTGRES_HOST_AUTH_METHOD=trust', image]);
  let ready = false;
  for (let attempt = 0; attempt < 20; attempt++) {
    try { call(['exec', name, 'pg_isready', '-U', 'postgres']); ready = true; break; }
    catch { await new Promise(resolve => setTimeout(resolve, 500)); }
  }
  if (!ready) throw new Error('PostgreSQL did not become ready');
  for (const [index, row] of restockRows.entries()) {
    const sql = row.modelOutput.trim();
    const item = { runId: row.evalRunId, executable: false,
      conflictInvariant: false, error: null };
    try {
      // -c sends one SQL string through libpq. Reject psql command syntax in
      // case a future psql version interprets it client-side.
      if (/(?:^|\n)\s*\\/.test(sql)) throw new Error('psql metacommand rejected');
      const states = [];
      for (const [world, seedConflict] of [false,true].entries()) {
        const database = `audit_${index}_${world}`;
        call(['exec', name, 'createdb', '-U', 'postgres', database]);
        psql(database, fixture);
        if (seedConflict) psql(database, existingLog);
        psql(database, sql);
        states.push(JSON.parse(psql(database, snapshot).trim()));
      }
      item.executable = true;
      item.states = states;
      const [noConflict,withConflict] = states.map(state => new Map(state.stocks));
      item.conflictInvariant = [1,2].every(id => noConflict.get(id) > (id === 1 ? 2 : 1) &&
        withConflict.get(id) === noConflict.get(id)) &&
        noConflict.get(3) === 12 && withConflict.get(3) === 12;
    } catch (error) {
      item.error = String(error.stderr || error.message).trim().slice(0, 600);
    }
    restockReport.push(item);
  }
  for (const [index,row] of rankingRows.entries()) {
    const database = `rank_${index}`;
    const item = {runId:row.evalRunId,executable:false,topUsersValid:false,error:null};
    try {
      call(['exec',name,'createdb','-U','postgres',database]);
      psql(database,rankingFixture);
      const sql = row.modelOutput.trim().replace(/\/\*[\s\S]*?\*\/\s*$/,'').replace(/;\s*$/,'');
      if (/(?:^|\n)\s*\\/.test(sql)) throw new Error('psql metacommand rejected');
      const result = psql(database,`SELECT coalesce(json_agg(row_to_json(t)), '[]'::json)
        FROM (${sql}) AS t`);
      const records = JSON.parse(result.trim());
      item.executable = true;
      item.rows = records.map(record => [record.city,record.username ?? record.name,
        record.order_no,Number(record.amount)]);
      const expected = [
        ['甲城','A1','A1-100',100],['甲城','A2','A2-90',90],['甲城','A3','A3-80',80],
        ['乙城','B1','B1-60',60],['乙城','B2','B2-50',50],['乙城','B3','B3-40',40],
      ];
      const canonical = values => values.map(value => JSON.stringify(value)).sort();
      const perCityOrdered = ['甲城','乙城'].every(city => {
        const amounts = item.rows.filter(record => record[0] === city).map(record => record[3]);
        return amounts.length === 3 && amounts.every((amount,i) => i === 0 || amounts[i-1] >= amount);
      });
      item.topUsersValid = perCityOrdered &&
        JSON.stringify(canonical(item.rows)) === JSON.stringify(canonical(expected));
    } catch (error) { item.error = String(error.stderr || error.message).trim().slice(0,600); }
    rankingReport.push(item);
  }
} finally {
  try { call(['stop', name]); } catch { /* container already stopped */ }
}
writeFileSync('data/pilots/structured-postgres-audit.json', JSON.stringify({
  restock: {scenarioId:'SO-CN-034',fixture:'same low-stock products with and without a preexisting restock log; prior log must not change stock increment',results:restockReport},
  ranking: {scenarioId:'SO-CN-013',fixture:'two cities, repeated high orders by one user, March boundaries',results:rankingReport},
}, null, 2) + '\n');
console.log(JSON.stringify({restock:restockReport.map(({executable,conflictInvariant,error}) =>
  ({executable,conflictInvariant,error})),ranking:rankingReport.map(({executable,topUsersValid,error}) =>
  ({executable,topUsersValid,error}))}));
